// Word-level diff for the AI-enhanced polish view (TICKET-77).
// LCS over whitespace-split words; returns ordered same/add/del tokens.

export interface DiffToken {
  type: 'same' | 'add' | 'del';
  text: string;
}

function tokenize(text: string): string[] {
  return text.trim() ? text.trim().split(/\s+/) : [];
}

export function wordDiff(original: string, polished: string): DiffToken[] {
  const a = tokenize(original);
  const b = tokenize(polished);
  const n = a.length;
  const m = b.length;

  const dp: number[][] = Array.from({ length: n + 1 }, () => new Array<number>(m + 1).fill(0));
  for (let i = n - 1; i >= 0; i -= 1) {
    for (let j = m - 1; j >= 0; j -= 1) {
      dp[i][j] = a[i] === b[j] ? dp[i + 1][j + 1] + 1 : Math.max(dp[i + 1][j], dp[i][j + 1]);
    }
  }

  const out: DiffToken[] = [];
  let i = 0;
  let j = 0;
  while (i < n && j < m) {
    if (a[i] === b[j]) {
      out.push({ type: 'same', text: a[i] });
      i += 1;
      j += 1;
    } else if (dp[i + 1][j] >= dp[i][j + 1]) {
      out.push({ type: 'del', text: a[i] });
      i += 1;
    } else {
      out.push({ type: 'add', text: b[j] });
      j += 1;
    }
  }
  while (i < n) out.push({ type: 'del', text: a[i++] });
  while (j < m) out.push({ type: 'add', text: b[j++] });
  return out;
}

export default { wordDiff };
